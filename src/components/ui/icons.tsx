import {
  BookOpen,
  CakeSlice,
  Cherry,
  ShoppingBasket,
  Bookmark,
  Castle,
  Crown,
  Droplets,
  Flower,
  Flower2,
  Gem,
  Heart,
  Key,
  Lock,
  Mail,
  Moon,
  Music,
  Scale,
  Scroll,
  Search,
  Smile,
  Sparkles,
  Sprout,
  Star,
  type LucideIcon,
} from 'lucide-react';

const ICONS: Record<string, LucideIcon> = {
  crown: Crown,
  flower: Flower,
  flower2: Flower2,
  key: Key,
  mail: Mail,
  sprout: Sprout,
  droplets: Droplets,
  sparkles: Sparkles,
  bookmark: Bookmark,
  book: BookOpen,
  scale: Scale,
  star: Star,
  heart: Heart,
  gem: Gem,
  moon: Moon,
  scroll: Scroll,
  lock: Lock,
  castle: Castle,
  search: Search,
  smile: Smile,
  music: Music,
  cherry: Cherry,
  basket: ShoppingBasket,
  cake: CakeSlice,
};

export function Icon({ name, className, size = 18 }: { name?: string; className?: string; size?: number }) {
  const C = (name && ICONS[name]) || Sparkles;
  return <C className={className} size={size} aria-hidden />;
}
